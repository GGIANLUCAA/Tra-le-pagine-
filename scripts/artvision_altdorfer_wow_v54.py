def fitted(draw,txt,face,size,max_width):
    while size>=24:
        font=ImageFont.truetype(face,size)
        bb=draw.textbbox((0,0),txt,font=font)
        if bb[2]-bb[0]<=max_width:return font
        size-=1
    raise RuntimeError('Opening text too long for legibility')

def brand(frame,alpha=1):
    alpha=max(0.,min(1.,float(alpha)))
    canvas=frame.convert('RGBA')
    layer=Image.new('RGBA',(W,H),(0,0,0,0));draw=ImageDraw.Draw(layer)
    draw.rounded_rectangle((56,1340,1024,1590),radius=10,fill=(5,8,13,round(190*alpha)))
    for txt,y,size in zip(TITLE_LINES,(1355,1413),(52,48)):
        font=fitted(draw,txt,SERIF,size,900)
        bb=draw.textbbox((0,0),txt,font=font)
        draw.text(((W-(bb[2]-bb[0]))/2,y),txt,font=font,fill=(255,251,243,round(255*alpha)))
    draw.line((130,1495,950,1495),fill=(218,198,168,round(186*alpha)),width=2)
    font=fitted(draw,ARTIST.upper(),SANS,33,900)
    bb=draw.textbbox((0,0),ARTIST.upper(),font=font)
    draw.text(((W-(bb[2]-bb[0]))/2,1521),ARTIST.upper(),font=font,fill=(255,251,243,round(255*alpha)))
    return Image.alpha_composite(canvas,layer).convert('RGB')

def cover(frame,path):
    brand(frame,1).save(path,quality=95,subsampling=0)

# No background image duplicates, no ghosting and no replicated edge-pixel stripes.
def whole_on_solid(src):
    bg=Image.new('RGB',(W,H),(12,15,22))
    whole=src.copy();whole.thumbnail((1030,1790),Image.Resampling.LANCZOS)
    x=(W-whole.width)//2;y=(H-whole.height)//2
    bg.paste(whole,(x,y))
    return bg

cinema.signature=brand
