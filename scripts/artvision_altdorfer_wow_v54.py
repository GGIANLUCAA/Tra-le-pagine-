def sha(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
    return h.hexdigest()

def ff(*args):
    subprocess.run([str(x) for x in args],check=True,timeout=240)

