#!/usr/bin/env python3
"""Source-locked conservative repair of historically incorrect theater sign and
unrealistic scarlet rider face in actual 1902 Finegrain 5th Vidu anchor.
Preserves the REAL original-film sign lettering/luminance, does not generate
letters, people, horse limbs, or object geometry. Free pixel-level correction.
"""
from pathlib import Path
import json,hashlib,cv2,numpy as np
R=Path("output/storia_ringling_1902_v1")
RAW=R/"FRAME_05_SOURCE.png"
IMG=R/"RINGLING_1902_SCENE05_VIDU_ANCHOR.jpg"
DONE=R/"RINGLING_1902_SCENE05_VIDU_SOURCE_REPAIRED.jpg"
QA=R/"SCENE05_CONSERVATIVE_HISTORIC_TEXT_FACE_REPAIR_QA.json"
def sha(path):
 h=hashlib.sha256()
 with path.open("rb") as f:
  for b in iter(lambda:f.read(1<<20),b""):h.update(b)
 return h.hexdigest()
def corr(a,b):
 def f(x):
  x=cv2.cvtColor(cv2.resize(x,(120,216)),cv2.COLOR_BGR2GRAY)
  return cv2.GaussianBlur(x,(7,7),0).ravel().astype(np.float32)
 x,y=f(a),f(b)
 return float(np.corrcoef(x,y)[0,1])
def main():
 q=json.loads((R/"FIFTH_VIDU_ANCHOR_PRESPEND_QA.json").read_text())
 if sha(IMG)!=q["photo_sha256"] or sha(RAW)!=q["source_frame_sha256"]:
  raise RuntimeError("REAL_1902_SOURCE_OR_FREE_FINEGRAIN_ANCHOR_SHA_CHANGED")
 original=cv2.imread(str(RAW))
 color=cv2.imread(str(IMG))
 if original.shape!=color.shape or color.shape[:2]!=(1280,720):
  raise RuntimeError("WRONG_FRAME_GEOMETRY_OR_CROP")
 # Finegrain hallucinated theatre letters; transfer ONLY true original 1902
 # luminance in the sign/sign brackets; source scene geometry is >=.998.
 lab=cv2.cvtColor(color,cv2.COLOR_BGR2LAB)
 origlab=cv2.cvtColor(original,cv2.COLOR_BGR2LAB)
 h,w=color.shape[:2]
 mask=np.zeros((h,w),np.float32)
 cv2.rectangle(mask,(360,402),(590,457),1,-1)
 mask=cv2.GaussianBlur(mask,(0,0),5)
 src=origlab[402:457,360:590,0].astype("float32")
 dst=lab[402:457,360:590,0].astype("float32")
 median_shift=float(np.median(dst)-np.median(src))
 replaced=np.clip(origlab[:,:,0].astype("float32")+median_shift,0,255)
 lab[:,:,0]=np.uint8(np.clip(lab[:,:,0].astype("float32")*(1-mask)+replaced*mask,0,255))
 color=cv2.cvtColor(lab,cv2.COLOR_LAB2BGR)
 # Face: retain exact source contours/eyes, reduce physically implausible
 # solid scarlet skin generated by Finegrain. This is color only, no fake face.
 hsv=cv2.cvtColor(color,cv2.COLOR_BGR2HSV)
 face=np.zeros((h,w),np.float32)
 cv2.ellipse(face,(245,426),(32,38),0,0,360,1,-1)
 face=cv2.GaussianBlur(face,(0,0),5)
 warm=(((hsv[:,:,0]<22)|(hsv[:,:,0]>170))&
       (hsv[:,:,1]>60)&(hsv[:,:,2]>65)).astype(np.float32)
 a=face*warm
 hsv[:,:,0]=np.uint8(np.clip(hsv[:,:,0].astype(np.float32)*(1-a)+11*a,0,179))
 hsv[:,:,1]=np.uint8(np.clip(hsv[:,:,1].astype(np.float32)*(1-a)+64*a,0,255))
 color=cv2.cvtColor(hsv,cv2.COLOR_HSV2BGR)
 score=corr(original,color)
 if score<.98:raise RuntimeError("TRUE_1902_SOURCE_GEOMETRY_LOST_"+str(score))
 if not cv2.imwrite(str(DONE),color,[cv2.IMWRITE_JPEG_QUALITY,96]):
  raise RuntimeError("CANNOT_SAVE_HISTORICALLY_CORRECTED_PRESPEND_ANCHOR")
 report={"status":"FREE_CONSERVATIVE_PHOTO_REPAIRED_PRESPEND_HUMAN_REVIEW_PENDING",
  "original_1902_frame_sha256":sha(RAW),
  "original_Finegrain_photo_sha256":sha(IMG),
  "corrected_photo_sha256":sha(DONE),
  "source_geometry_corr":round(score,4),
  "corrections":["original historical theater-sign lettering is preserved from the TRUE black and white film pixels (not inferred letters)",
                 "unrealistic generated scarlet rider skin tint reduced without changing body/face geometry"],
  "remaining_artistic_uncertainty":["face anatomy accuracy from degraded source", "Vidu motion not yet generated or verified"],
  "provider_video_posts":0,"credits_spent":0,
  "no_publication_approved":True,"rights_italy":"NOT_CLEARED"}
 QA.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n")
 print("RINGLING_1902_FIFTH_FRAME_TEXT_ACTUAL_SOURCE_REPAIRED",
       "photo_sha",sha(DONE),"corr",round(score,4),"paid_vidu_posts",0,flush=True)
if __name__=="__main__":main()
